import asyncio
import os
import sqlite3
from pathlib import Path

import psycopg
from psycopg.rows import dict_row

DEFAULT_SQLITE = Path(__file__).resolve().with_name("audit.sqlite3")


class Database:
    def __init__(self, connection, postgres=False):
        self.connection = connection
        self.postgres = postgres
        self.lock = asyncio.Lock()

    @classmethod
    async def open(cls):
        url = os.getenv("DATABASE_URL", "").strip()
        if url:
            connection = await psycopg.AsyncConnection.connect(
                url, row_factory=dict_row, autocommit=True, connect_timeout=5,
                options="-c statement_timeout=10000 -c lock_timeout=5000",
            )
            return cls(connection, postgres=True)
        connection = sqlite3.connect(os.getenv("DNS_AUDIT_DB", str(DEFAULT_SQLITE)), isolation_level=None)
        connection.row_factory = sqlite3.Row
        return cls(connection)

    async def _query(self, sql, params=(), *, fetch=False):
        if self.postgres:
            async with self.connection.cursor() as cursor:
                await cursor.execute(sql.replace("?", "%s"), params)
                return await cursor.fetchall() if fetch else None
        cursor = self.connection.execute(sql, params)
        try:
            return cursor.fetchall() if fetch else None
        finally:
            cursor.close()

    async def execute(self, sql, params=()):
        async with self.lock:
            await self._query(sql, params)

    async def fetch(self, sql, params=()):
        async with self.lock:
            return await self._query(sql, params, fetch=True)

    async def one(self, sql, params=()):
        rows = await self.fetch(sql, params)
        return rows[0] if rows else None

    async def initialize(self, seed_members=None):
        audit_id = "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" if self.postgres else "INTEGER PRIMARY KEY"
        await self.execute(f"""
            CREATE TABLE IF NOT EXISTS dns_audit (
                id {audit_id}, created_at TEXT NOT NULL, actor TEXT NOT NULL,
                channel TEXT NOT NULL, domain TEXT NOT NULL, action TEXT NOT NULL,
                status TEXT NOT NULL, before_json TEXT, after_json TEXT
            )
        """)
        await self.execute("""
            CREATE TABLE IF NOT EXISTS dns_members (
                name TEXT PRIMARY KEY, role TEXT NOT NULL, credential_hash TEXT NOT NULL UNIQUE,
                issued_at TEXT, revoked_at TEXT
            )
        """)
        await self.execute("CREATE INDEX IF NOT EXISTS dns_audit_actor_id ON dns_audit (actor, id)")
        for digest, (name, role) in (seed_members or {}).items():
            await self.execute(
                "INSERT INTO dns_members (name, role, credential_hash) VALUES (?, ?, ?) "
                "ON CONFLICT(name) DO NOTHING", (name, role, digest),
            )

    async def create_member(self, name, role, digest, now):
        sql = """
            INSERT INTO dns_members (name, role, credential_hash, issued_at)
            SELECT ?, ?, ?, ?
            WHERE NOT EXISTS (SELECT 1 FROM dns_members WHERE LOWER(name) = LOWER(?))
            RETURNING name
        """
        params = (name, role, digest, now, name)
        if not self.postgres:
            return await self.one(sql, params)
        async with self.lock, self.connection.transaction():
            await self._query("LOCK TABLE dns_members IN SHARE ROW EXCLUSIVE MODE")
            rows = await self._query(sql, params, fetch=True)
            return rows[0] if rows else None

    async def import_sqlite(self, filename):
        if not self.postgres:
            raise ValueError("Configure DATABASE_URL for PostgreSQL first.")
        source = sqlite3.connect(Path(filename).resolve().as_uri() + "?mode=ro", uri=True)
        try:
            source.execute("BEGIN")
            members = source.execute(
                "SELECT name, role, credential_hash, issued_at, revoked_at FROM dns_members"
            ).fetchall()
            events = source.execute(
                "SELECT id, created_at, actor, channel, domain, action, status, before_json, after_json FROM dns_audit ORDER BY id"
            ).fetchall()
        finally:
            source.close()

        async with self.lock, self.connection.transaction():
            await self._query("LOCK TABLE dns_members, dns_audit IN ACCESS EXCLUSIVE MODE")
            for table in ("dns_members", "dns_audit"):
                if await self._query(f"SELECT 1 FROM {table} LIMIT 1", fetch=True):
                    raise ValueError("The target database already has DNS data. Migration requires an empty target.")
            async with self.connection.cursor() as cursor:
                async with cursor.copy("COPY dns_members (name, role, credential_hash, issued_at, revoked_at) FROM STDIN") as copy:
                    for member in members:
                        await copy.write_row(member)
                async with cursor.copy(
                    "COPY dns_audit (id, created_at, actor, channel, domain, action, status, before_json, after_json) FROM STDIN"
                ) as copy:
                    for event in events:
                        await copy.write_row(event)
                if events:
                    await cursor.execute(
                        "SELECT setval(pg_get_serial_sequence('dns_audit', 'id'), "
                        "(SELECT GREATEST(MAX(id), 1) FROM dns_audit))"
                    )
        return len(members), len(events)

    async def close(self):
        if self.postgres:
            await self.connection.close()
        else:
            self.connection.close()
